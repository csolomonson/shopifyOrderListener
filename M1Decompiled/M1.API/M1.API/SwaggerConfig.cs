		stringBuilder.AppendLine("### Paging Parameters\n");
		stringBuilder.AppendLine("The parameters `pageSize` and `pageNumber` can be provided separately but can be combined to implement server-side paging of results.\n");
		stringBuilder.AppendLine("Example:\n");
		stringBuilder.AppendLine("`?pageSize=100&pageNumber=5`\n");
		stringBuilder.AppendLine("Page Size defaults to 1000, which is also the maximum.\n");
		stringBuilder.AppendLine("Page Number defaults to 0, which is first page of results.\n");
		stringBuilder.AppendLine("### Order By Expressions\n");
		stringBuilder.AppendLine("For resources that support sorting, the order by expression is specified by adding the orderBy query string parameter in the format `M1Field[Operator],M1Field[Operator]`. The following operators are supported: `Asc` or `Desc`\n");
		stringBuilder.AppendLine("Example:\n");
		stringBuilder.AppendLine("`?orderBy=impPartID[Asc],impPartType[Desc]`\n");
		stringBuilder.AppendLine("### Concurrency Checking\n");
		stringBuilder.AppendLine("Unless otherwise noted, the PUT endpoint requires the row version field from all standard tables to be specified. This will ensure a concurrency check is performed and will make it less likely data is overwritten. If the row version is not the current value, the server will respond with an HTTP 409 Conflict status. This is likely an indication that another user has modified this record since you retrieved it. To resolve, retrieve the record again and include the current row version value.\n");
