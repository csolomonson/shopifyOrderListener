		stringBuilder.AppendLine("{");
		stringBuilder.AppendLine("    \"description\": \"\",");
		stringBuilder.AppendLine("    \"status\": \"Error\",");
		stringBuilder.AppendLine("    \"payloadID\": \"\",");
		stringBuilder.AppendLine("    \"errors\": [");
